#!/bin/sh
# Regenerates pass_barrier_spv.h, the shaders of pass_barrier_test.c and pass_barrier_icd_test.c
# (glslangValidator). Each array's name ends in what pb_spirv_geo_scan must find in it: _reads (image
# reads), _writes (memory writes), _reads_writes or _none.
set -eu
cd "$(dirname "$0")"
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
shader() { # name stage [target environment]
    cat > "$T/$1.$2"
    glslangValidator -V --target-env "${3:-vulkan1.1}" --vn "pb_$1" -o "$T/$1.h" "$T/$1.$2" >/dev/null
    cat "$T/$1.h" >> "$T/all.h"
}
shader vert_sample_reads vert <<'GLSL'
#version 450
layout(binding = 0) uniform sampler2D heights;
layout(location = 0) in vec2 uv;
void main() { gl_Position = vec4(uv, textureLod(heights, uv, 0.0).r, 1.0); }
GLSL
shader vert_texel_buffer_none vert <<'GLSL'
#version 450
layout(binding = 0) uniform samplerBuffer offsets;
layout(binding = 1, r32f) uniform readonly imageBuffer scales;
void main() { gl_Position = texelFetch(offsets, gl_VertexIndex) * imageLoad(scales, gl_InstanceIndex).r; }
GLSL
shader vert_storage_image_reads vert <<'GLSL'
#version 450
layout(binding = 0, rgba8) uniform readonly image2D positions;
void main() { gl_Position = imageLoad(positions, ivec2(gl_VertexIndex, 0)); }
GLSL
shader vert_plain_none vert <<'GLSL'
#version 450
layout(binding = 0) uniform Constants { mat4 transform; };
layout(location = 0) in vec4 position;
void main() { gl_Position = transform * position; }
GLSL
shader tese_separate_reads tese <<'GLSL'
#version 450
layout(triangles) in;
layout(binding = 0) uniform texture2D displacement;
layout(binding = 1) uniform sampler linearSampler;
void main() {
    vec4 p = gl_in[0].gl_Position * gl_TessCoord.x + gl_in[1].gl_Position * gl_TessCoord.y + gl_in[2].gl_Position * gl_TessCoord.z;
    gl_Position = p + textureLod(sampler2D(displacement, linearSampler), p.xy, 0.0);
}
GLSL
shader geom_fetch_reads geom <<'GLSL'
#version 450
layout(points) in;
layout(points, max_vertices = 1) out;
layout(binding = 0) uniform sampler2D table[4];
void main() {
    gl_Position = gl_in[0].gl_Position + texelFetch(table[gl_PrimitiveIDIn & 3], ivec2(0), 0);
    EmitVertex();
}
GLSL
shader frag_sample_none frag <<'GLSL'
#version 450
layout(binding = 0) uniform sampler2D colour;
layout(location = 0) in vec2 uv;
layout(location = 0) out vec4 result;
void main() { result = texture(colour, uv); }
GLSL
shader vert_ssbo_writes vert <<'GLSL'
#version 450
layout(binding = 0) buffer Positions { vec4 positions[]; };
void main() { positions[gl_VertexIndex] = vec4(1.0); gl_Position = vec4(0.0); }
GLSL
# Uniform storage class and BufferBlock
shader vert_ssbo_uniform_writes vert vulkan1.0 <<'GLSL'
#version 450
layout(binding = 0) buffer Positions { vec4 positions[]; };
void main() { positions[gl_VertexIndex] = vec4(1.0); gl_Position = vec4(0.0); }
GLSL
shader vert_ssbo_readonly_none vert <<'GLSL'
#version 450
layout(binding = 0) readonly buffer Positions { vec4 positions[]; };
void main() { gl_Position = positions[gl_VertexIndex]; }
GLSL
shader vert_image_store_writes vert <<'GLSL'
#version 450
layout(binding = 0, rgba8) uniform writeonly image2D marks;
void main() { imageStore(marks, ivec2(gl_VertexIndex, 0), vec4(1.0)); gl_Position = vec4(0.0); }
GLSL
shader vert_atomic_writes vert <<'GLSL'
#version 450
layout(binding = 0) buffer Counter { uint vertices; };
void main() { atomicAdd(vertices, 1u); gl_Position = vec4(0.0); }
GLSL
shader vert_buffer_reference_writes vert vulkan1.2 <<'GLSL'
#version 450
#extension GL_EXT_buffer_reference : require
layout(buffer_reference, std430) buffer Positions { vec4 position; };
layout(push_constant) uniform Constants { Positions out_; };
void main() { out_.position = vec4(1.0); gl_Position = vec4(0.0); }
GLSL
shader geom_ssbo_writes geom <<'GLSL'
#version 450
layout(points) in;
layout(points, max_vertices = 1) out;
layout(binding = 0) buffer Primitives { uint primitives[]; };
void main() {
    primitives[gl_PrimitiveIDIn] = 1u;
    gl_Position = gl_in[0].gl_Position;
    EmitVertex();
}
GLSL
shader vert_sample_ssbo_reads_writes vert <<'GLSL'
#version 450
layout(binding = 0) uniform sampler2D heights;
layout(binding = 1) buffer Heights { float seen[]; };
void main() {
    float h = textureLod(heights, vec2(0.5), 0.0).r;
    seen[gl_VertexIndex] = h;
    gl_Position = vec4(0.0, 0.0, h, 1.0);
}
GLSL
shader frag_ssbo_none frag <<'GLSL'
#version 450
layout(binding = 0) buffer Fragments { uint fragments; };
layout(location = 0) out vec4 result;
void main() { atomicAdd(fragments, 1u); result = vec4(1.0); }
GLSL
shader vert_xfb_none vert <<'GLSL'
#version 450
layout(location = 0, xfb_buffer = 0, xfb_offset = 0) out vec4 captured;
void main() { captured = vec4(1.0); gl_Position = vec4(0.0); }
GLSL
{ echo "/* Generated by pass_barrier_gen.sh. */"; cat "$T/all.h"; } > pass_barrier_spv.h
