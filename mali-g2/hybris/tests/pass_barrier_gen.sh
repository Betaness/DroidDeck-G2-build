#!/bin/sh
# Regenerates pass_barrier_spv.h, the shaders of pass_barrier_test.c (glslangValidator). Each array's
# name ends in _reads or _none: what pb_spirv_geo_image_reads must say about it.
set -eu
cd "$(dirname "$0")"
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
shader() { # name stage
    cat > "$T/$1.$2"
    glslangValidator -V --target-env vulkan1.1 --vn "pb_$1" -o "$T/$1.h" "$T/$1.$2" >/dev/null
    cat "$T/$1.h" >> "$T/all.h"
}
shader vert_sample_reads vert <<'GLSL'
#version 450
layout(binding = 0) uniform sampler2D heights;
layout(location = 0) in vec2 uv;
void main() { gl_Position = vec4(uv, textureLod(heights, uv, 0.0).r, 1.0); }
GLSL
shader vert_texel_buffer_none vert <<'GLSL'
#version 450
layout(binding = 0) uniform samplerBuffer offsets;
layout(binding = 1, r32f) uniform readonly imageBuffer scales;
void main() { gl_Position = texelFetch(offsets, gl_VertexIndex) * imageLoad(scales, gl_InstanceIndex).r; }
GLSL
shader vert_storage_image_reads vert <<'GLSL'
#version 450
layout(binding = 0, rgba8) uniform readonly image2D positions;
void main() { gl_Position = imageLoad(positions, ivec2(gl_VertexIndex, 0)); }
GLSL
shader vert_plain_none vert <<'GLSL'
#version 450
layout(binding = 0) uniform Constants { mat4 transform; };
layout(location = 0) in vec4 position;
void main() { gl_Position = transform * position; }
GLSL
shader tese_separate_reads tese <<'GLSL'
#version 450
layout(triangles) in;
layout(binding = 0) uniform texture2D displacement;
layout(binding = 1) uniform sampler linearSampler;
void main() {
    vec4 p = gl_in[0].gl_Position * gl_TessCoord.x + gl_in[1].gl_Position * gl_TessCoord.y + gl_in[2].gl_Position * gl_TessCoord.z;
    gl_Position = p + textureLod(sampler2D(displacement, linearSampler), p.xy, 0.0);
}
GLSL
shader geom_fetch_reads geom <<'GLSL'
#version 450
layout(points) in;
layout(points, max_vertices = 1) out;
layout(binding = 0) uniform sampler2D table[4];
void main() {
    gl_Position = gl_in[0].gl_Position + texelFetch(table[gl_PrimitiveIDIn & 3], ivec2(0), 0);
    EmitVertex();
}
GLSL
shader frag_sample_none frag <<'GLSL'
#version 450
layout(binding = 0) uniform sampler2D colour;
layout(location = 0) in vec2 uv;
layout(location = 0) out vec4 result;
void main() { result = texture(colour, uv); }
GLSL
{ echo "/* Generated by pass_barrier_gen.sh. */"; cat "$T/all.h"; } > pass_barrier_spv.h
